type Ctx = {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (k: string, params?: Record<string, string | number>) => string;
};
const I18nCtx = createContext<Ctx | null>(null);

const STORAGE_KEY = "bridgecn.locale";

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY) as Locale | null;
      if (saved && saved in dicts) setLocaleState(saved);
    } catch {
      /* ignore */
    }
  }, []);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* ignore */
    }
  }, []);

  const value = useMemo<Ctx>(() => {
    const dict = dicts[locale];
    const format = (s: string, params?: Record<string, string | number>) =>
      params
        ? s.replace(/\{(\w+)\}/g, (_, k) => (params[k] != null ? String(params[k]) : `{${k}}`))
        : s;
    return {
      locale,
      setLocale,
      t: (k: string, params?: Record<string, string | number>) =>
        format(dict[k] ?? en[k] ?? k, params),
    };
  }, [locale, setLocale]);

  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nCtx);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}

export function useT() {
  return useI18n().t;
}
